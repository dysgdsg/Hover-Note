$ErrorActionPreference = 'Stop'

$root      = Split-Path -Parent $PSScriptRoot
$csc       = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe'
$rulesJson = Join-Path $root 'rules\rules.json'
$objDir    = Join-Path $root 'obj'
$binDir    = Join-Path $root 'bin'
$genPath   = Join-Path $objDir 'RulesData.g.cs'
$nl        = [Environment]::NewLine

New-Item -ItemType Directory -Path $objDir -Force | Out-Null
New-Item -ItemType Directory -Path $binDir -Force | Out-Null

# ---------- 1. 由 rules.json 生成 RulesData.g.cs ----------
$data = Get-Content -LiteralPath $rulesJson -Raw -Encoding UTF8 | ConvertFrom-Json

function Esc([string]$s) {
    if ($null -eq $s) { return '' }
    return $s.Replace('"', '""')
}

function KindOf([string]$k) {
    switch ($k) {
        'exact'  { return 'RuleKind.Exact' }
        'prefix' { return 'RuleKind.Prefix' }
        'suffix' { return 'RuleKind.Suffix' }
        'glob'   { return 'RuleKind.Glob' }
        default  { throw "rules.json 里有不认识的 kind: $k" }
    }
}

function LevelOf([string]$l) {
    switch ($l) {
        'safe'    { return 'TipLevel.Safe' }
        'caution' { return 'TipLevel.Caution' }
        'danger'  { return 'TipLevel.Danger' }
        'unknown' { return 'TipLevel.Unknown' }
        default   { throw "rules.json 里有不认识的 level: $l" }
    }
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// <auto-generated> 由 tools/build.ps1 从 rules/rules.json 生成，请勿手改。</auto-generated>')
$lines.Add('namespace HoverNote')
$lines.Add('{')
$lines.Add('    internal static class RulesData')
$lines.Add('    {')
$lines.Add('        public static readonly Rule[] All = new Rule[]')
$lines.Add('        {')

foreach ($r in $data.rules) {
    $applies = if ($r.applies) { $r.applies } else { 'both' }
    switch ($applies) {
        'both'  { $files = 'true';  $dirs = 'true' }
        'files' { $files = 'true';  $dirs = 'false' }
        'dirs'  { $files = 'false'; $dirs = 'true' }
        default { throw "rules.json 里有不认识的 applies: $applies" }
    }
    $priority = if ($null -ne $r.priority) { [int]$r.priority } else { 0 }

    $line = '            new Rule("' + (Esc $r.id) + '", @"' + (Esc $r.pattern) + '", ' + (KindOf $r.kind) + ', ' + (LevelOf $r.level) + ', @"' + (Esc $r.explain) + '", ' + $files + ', ' + $dirs + ', ' + $priority + '),'
    $lines.Add($line)
}

$lines.Add('        };')
$lines.Add('    }')
$lines.Add('}')

$enc = New-Object System.Text.UTF8Encoding($true)
[System.IO.File]::WriteAllText($genPath, ($lines -join $nl) + $nl, $enc)

# ---------- 2. 编译（旧 DLL 被 explorer 占用时自动改名） ----------
$dll = Join-Path $binDir 'HoverNote.dll'
if (Test-Path -LiteralPath $dll) {
    try {
        $fs = [System.IO.File]::Open($dll, 'Open', 'ReadWrite', 'None')
        $fs.Close()
    } catch {
        $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
        $bak = Join-Path $binDir ('HoverNote.locked-' + $stamp + '.dll')
        Move-Item -LiteralPath $dll -Destination $bak
        Write-Output ('[提示] 旧 DLL 被 explorer 占用，已改名为 ' + (Split-Path -Leaf $bak) + '（重启 explorer 后可删）')
    }
}

& $csc /nologo /codepage:65001 /target:library /platform:x64 /optimize+ /out:$dll "$root\src\HoverNote.cs" $genPath
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

& $csc /nologo /codepage:65001 /target:exe /platform:x64 /optimize+ /out:"$binDir\TestHarness.exe" "$root\src\TestHarness.cs"
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# ---------- 3. 打包：Uninstall.exe 与 HoverNote-Setup.exe ----------
$distDir  = Join-Path $root 'dist'
New-Item -ItemType Directory -Path $distDir -Force | Out-Null

$winForms = '/r:System.Windows.Forms.dll'
$drawing  = '/r:System.Drawing.dll'
$manifest = Join-Path $root 'src\app.manifest'

& $csc /nologo /codepage:65001 /target:winexe /platform:x64 /optimize+ /win32manifest:$manifest /out:"$distDir\Uninstall.exe" $winForms $drawing "$root\src\Uninstall.cs"
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$resDll = '/resource:' + (Join-Path $binDir 'HoverNote.dll') + ',app.dll'
$resUn  = '/resource:' + (Join-Path $distDir 'Uninstall.exe') + ',uninstall.exe'
$resRdm = '/resource:' + (Join-Path $root 'docs\README.txt') + ',readme.txt'

& $csc /nologo /codepage:65001 /target:winexe /platform:x64 /optimize+ /win32manifest:$manifest /out:"$distDir\HoverNote-Setup.exe" $winForms $drawing $resDll $resUn $resRdm "$root\src\Setup.cs"
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Output ('规则条数: ' + $data.rules.Count)
Get-ChildItem $binDir | Select-Object Name, Length | Format-Table -AutoSize
Get-ChildItem $distDir | Select-Object Name, Length | Format-Table -AutoSize
